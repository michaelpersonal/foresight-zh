static void log_results(const char *fn, u64 list_pp) {
  u64 list = 0, hdr[2];
  if (!list_pp || !safe_read(list_pp, &list, 8) || !list) return;
  if (!safe_read(list, hdr, sizeof hdr) || !hdr[0] || hdr[1] > 64) return;
  for (u64 k = 0; k < hdr[1]; k++) {
    u64 item[6];
    char txt[1024] = {0};
    if (!safe_read(hdr[0] + k * 0x30, item, sizeof item)) break;
    if (item[0]) read_cstr(item[0], txt, sizeof txt);
    logf_("  result %s[%llu] final=%d f10=%lld f18=%lld map=%#llx/%llu \"%s\"", fn, k,
          (int)(item[1] & 0xff), (long long)item[2], (long long)item[3], item[4], item[5], txt);
    for (u64 m = 0; item[4] && m < item[5] && m < 8; m++) {
      u64 kv[2]; char key[128] = {0}, val[256] = {0};
      if (!safe_read(item[4] + m * 16, kv, sizeof kv)) break;
      if (kv[0]) read_cstr(kv[0], key, sizeof key);
      if (kv[1]) read_cstr(kv[1], val, sizeof val);
      logf_("    meta %s=%s", key, val);
    }
  }
}

// Foresight measures transcripts in space-separated words: it only builds live
// chat chunks and offers a summary once there are enough of them, so unspaced
// Chinese looks nearly empty. Put a hair space (U+200A, near-invisible) at every
// boundary next to a CJK character; the chat bridge strips them again.
static int is_cjk(uint32_t c) {
  return (c >= 0x2E80 && c <= 0x9FFF) || (c >= 0xAC00 && c <= 0xD7AF) || (c >= 0xF900 && c <= 0xFAFF) ||
         (c >= 0xFF00 && c <= 0xFFEF) || (c >= 0x20000 && c <= 0x3FFFF);
}

static uint32_t utf8_next(const unsigned char **p) {
  const unsigned char *s = *p;
  uint32_t c = s[0];
  int n = c < 0x80 ? 1 : c < 0xE0 ? 2 : c < 0xF0 ? 3 : 4;
  if (n > 1) c &= 0xFF >> (n + 1);
  for (int i = 1; i < n && s[i]; i++) c = (c << 6) | (s[i] & 0x3F);
  for (int i = 0; i < n && **p; i++) (*p)++;
  return c;
}

static char *space_cjk(char *text) {
  size_t len = strlen(text);
  char *out = malloc(len * 4 + 1), *o = out;
  const unsigned char *p = (const unsigned char *)text;
  uint32_t prev = 0;
  while (*p) {
    const unsigned char *start = p;
    uint32_t c = utf8_next(&p);
    int space = c == ' ' || c == '\n' || c == '\t' || c == 0x200A;
    int prev_space = prev == 0 || prev == ' ' || prev == '\n' || prev == '\t' || prev == 0x200A;
    if (!space && !prev_space && (is_cjk(c) || is_cjk(prev))) {
      memcpy(o, "\xE2\x80\x8A", 3);
      o += 3;
    }
    memcpy(o, start, p - start);
    o += p - start;
    prev = c;
  }
  *o = 0;
  free(text);
  return out;
}

// Builds an OdmlTranscriptionResultList / OdmlStatus exactly as the native
// library does (malloc'ed; freed by OdmlDestroyTranscriptionResultList / Status).
static void *make_result_list(SvResult *r, int n) {
  u64 *list = malloc(16);
  uint8_t *items = n > 0 ? calloc(n, 0x30) : NULL;
  for (int k = 0; k < n; k++) {
    uint8_t *it = items + k * 0x30;
    r[k].text = space_cjk(r[k].text);
    *(char **)it = r[k].text;              // text
    it[8] = 1;                             // is_final
    *(long long *)(it + 0x10) = r[k].start_us;
    *(long long *)(it + 0x18) = r[k].end_us;
    if (g_trace) logf_("  sensevoice [%.2fs-%.2fs] \"%s\"", r[k].start_us / 1e6, r[k].end_us / 1e6, r[k].text);
  }
  list[0] = (u64)items;
  list[1] = (u64)n;
  return list;
}

static void *make_ok_status(void) {
  OdmlStatus *st = malloc(sizeof *st);
  st->code = 0;
  st->message = NULL;
  return st;
}

// Returns 1 if SenseVoice handled the call (results/status written), 0 to fall
// through to Foresight's own engine.
static int sensevoice_call(int i, u64 a[8]) {
  SvResult r[16];
  int n;
  u64 results_pp, status_pp;
  if (i == H_TRANSCRIBE) {  // (proc, const float *samples, size_t n, bool, int stream, results**, status**)
    n = sv_push((int)a[4], (const float *)a[1], (int)a[2], r, 16);
    results_pp = a[5], status_pp = a[6];
  } else {                  // FinishStream: (proc, int stream, results**, status**)
    n = sv_finish((int)a[1], r, 16);
    results_pp = a[2], status_pp = a[3];
  }
  if (n < 0) return 0;
  if (results_pp) *(void **)results_pp = make_result_list(r, n);
  else for (int k = 0; k < n; k++) free(r[k].text);
  if (status_pp) *(void **)status_pp = make_ok_status();
  return 1;
}

static u64 call_hook(int i, u64 a[8]) {
  Hook *h = &g_hooks[i];
  u64 saved_path = 0;

  if (g_engine == ENGINE_SENSEVOICE && (i == H_TRANSCRIBE || i == H_FINISH) && sensevoice_call(i, a))
    return 1;

  if (i == H_ENGINE) {
    // a[0] points at the engine options struct; field 0 is the model path. This
    // C API is only used for the ASR engine (Foresight's own model is decrypted
    // to ~/Library/Caches before loading; the Gemma chat model loads elsewhere).
    u64 path_ptr = 0;
    char path[1024] = {0};
    g_redirected = 0;
    if (g_trace) {
      int ok1 = safe_read(a[0], &path_ptr, 8);
      int ok2 = ok1 && path_ptr && read_cstr(path_ptr, path, sizeof path);
      logf_("engine opts %#llx path_ptr %#llx ok=%d/%d path=%s", a[0], path_ptr, ok1, ok2, path);
    }
    if (g_engine == ENGINE_GEMMA && safe_read(a[0], &path_ptr, 8) && path_ptr &&
        read_cstr(path_ptr, path, sizeof path) && strstr(path, ".litertlm")) {
      saved_path = path_ptr;
      *(u64 *)a[0] = (u64)g_asr_model;
      g_redirected = 1;
      logf_("ASR engine: %s -> %s", path, g_asr_model);
    }
  }
  if (i == H_PIPELINE && g_engine == ENGINE_GEMMA && g_redirected && g_override) {
    a[1] = (u64)g_override;
    a[2] = g_override_len;
  }

  u64 r = h->real(a[0], a[1], a[2], a[3], a[4], a[5], a[6], a[7]);

  if (saved_path) *(u64 *)a[0] = saved_path;  // the caller owns and frees its own string
  OdmlStatus *s = (h->status_arg >= 0 && a[h->status_arg]) ? *(OdmlStatus **)a[h->status_arg] : 0;
  int failed = s && s->code != 0;
  if (failed || (g_trace && i != H_TRANSCRIBE) || i == H_ENGINE || i == H_PIPELINE)
    logf_("%s -> %s", h->name, s ? (s->message ? s->message : "OK") : "(no status)");
  if (g_trace && h->result_arg >= 0) log_results(h->name, a[h->result_arg]);
  return r;
}

