enum { ENGINE_NONE, ENGINE_SENSEVOICE, ENGINE_GEMMA };
static int g_engine;
static char g_asr_model[1024];  // replacement ASR model path ("" = disabled)
static void *g_override;        // replacement SpeechPipelineOptionsProto bytes
static u64 g_override_len;

static void read_line_file(const char *path, char *out, size_t n) {
  FILE *f = fopen(path, "r");
  if (!f) return;
  if (fgets(out, (int)n, f)) out[strcspn(out, "\r\n")] = 0;
  fclose(f);
}

static void load_config(void) {
  char p[1024], engine[64] = "persian";
  snprintf(p, sizeof p, "%s/tools/foresight-zh/engine", g_home);
  read_line_file(p, engine, sizeof engine);
  if (strcmp(engine, "persian") == 0 || strcmp(engine, "fa") == 0) {
    if (sv_available(g_home, SV_LANG_PERSIAN)) {
      g_engine = ENGINE_SENSEVOICE;
      logf_("config: engine=persian");
      sv_start_loading();
      return;
    }
    logf_("config: persian model not installed (run setup-persian.sh) - trying sensevoice");
    strcpy(engine, "sensevoice");
  }
  if (strcmp(engine, "sensevoice") == 0) {
    if (sv_available(g_home, SV_LANG_SENSEVOICE)) {
      g_engine = ENGINE_SENSEVOICE;
      logf_("config: engine=sensevoice");
      sv_start_loading();
      return;
    }
    logf_("config: sensevoice not installed - trying gemma");
  }
  snprintf(g_asr_model, sizeof g_asr_model,
           "%s/local-llm/models/special/foresight-zh/zh_asr_gemma4e2b_v3.litertlm", g_home);
  snprintf(p, sizeof p, "%s/tools/foresight-zh/asr_model_path", g_home);
  read_line_file(p, g_asr_model, sizeof g_asr_model);
  struct stat st;
  if (g_asr_model[0] && stat(g_asr_model, &st) != 0) {
    logf_("config: ASR model %s missing - redirect disabled, app stays English", g_asr_model);
    g_asr_model[0] = 0;
  }

  snprintf(p, sizeof p, "%s/tools/foresight-zh/pipeline_override.pb", g_home);
  FILE *f = fopen(p, "rb");
  if (f) {
    fseek(f, 0, SEEK_END);
    long n = ftell(f);
    fseek(f, 0, SEEK_SET);
    g_override = malloc(n);
    g_override_len = fread(g_override, 1, n, f);
    fclose(f);
  }
  if (g_asr_model[0]) g_engine = ENGINE_GEMMA;
  logf_("config: engine=%s asr_model=%s override=%llu bytes", g_engine ? "gemma" : "none (English)",
        g_asr_model[0] ? g_asr_model : "(none)", g_override_len);
}

// ---------------------------------------------------------- filter patch ---

static void patch_ascii_filter(void) {
  static const char orig[] = "[^\\x20-\\x7E\\n\\r]";
  static const char repl[] = "[\\x00-\\x08\\x7F]+";
  _Static_assert(sizeof orig == sizeof repl, "replacement must keep the string length");
  const size_t n = sizeof orig - 1;

  const struct mach_header_64 *mh = NULL;
  for (uint32_t k = 0; k < _dyld_image_count(); k++) {
    const char *name = _dyld_get_image_name(k);
    if (name && strstr(name, "/Contents/MacOS/Foresight")) {
      mh = (const struct mach_header_64 *)_dyld_get_image_header(k);
      break;
    }
  }
  if (!mh) {
    logf_("filter patch: Foresight image not found");
    return;
  }
  unsigned long size = 0;
  uint8_t *sect = getsectiondata(mh, "__TEXT", "__const", &size);
  if (!sect) {
    logf_("filter patch: __TEXT,__const not found");
    return;
  }
  uint8_t *hit = memmem(sect, size, orig, n);
  if (!hit) {
    if (memmem(sect, size, repl, n)) logf_("filter patch: already applied");
    else logf_("filter patch: ASCII filter regex not found (app changed?) - Chinese may be stripped");
    return;
  }
  if (memmem(hit + n, size - (hit + n - sect), orig, n)) {
    logf_("filter patch: regex found more than once - refusing to guess");
    return;
  }
  u64 addr = (u64)hit;
  u64 page = addr & ~(u64)(vm_page_size - 1);
  u64 len = ((addr + n) - page + vm_page_size - 1) & ~(u64)(vm_page_size - 1);
  kern_return_t kr = mach_vm_protect(mach_task_self(), page, len, FALSE,
                                     VM_PROT_READ | VM_PROT_WRITE | VM_PROT_COPY);
  if (kr != KERN_SUCCESS) {
    logf_("filter patch: vm_protect failed (%d)", kr);
    return;
  }
  memcpy(hit, repl, n);
  mach_vm_protect(mach_task_self(), page, len, FALSE, VM_PROT_READ);
  logf_("filter patch: applied at %p", hit);
}

