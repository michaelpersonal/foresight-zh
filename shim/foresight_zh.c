static pthread_mutex_t g_mu = PTHREAD_MUTEX_INITIALIZER;
static FILE *g_log;
static int g_trace;
static char g_home[512];

void logf_(const char *fmt, ...) {
  pthread_mutex_lock(&g_mu);
  if (!g_log) {
    char dir[700], p[800];
    snprintf(dir, sizeof dir, "%s/Library/Logs/foresight-zh", g_home);
    mkdir(dir, 0755);
    snprintf(p, sizeof p, "%s/shim.log", dir);
    g_log = fopen(p, "a");
  }
  if (g_log) {
    struct timespec ts;
    clock_gettime(CLOCK_REALTIME, &ts);
    struct tm tm;
    localtime_r(&ts.tv_sec, &tm);
    char t[32];
    strftime(t, sizeof t, "%Y-%m-%d %H:%M:%S", &tm);
    fprintf(g_log, "[%s.%03ld] ", t, ts.tv_nsec / 1000000);
    va_list ap;
    va_start(ap, fmt);
    vfprintf(g_log, fmt, ap);
    va_end(ap);
    fputc('\n', g_log);
    fflush(g_log);
  }
  pthread_mutex_unlock(&g_mu);
}

static int safe_read(u64 addr, void *out, u64 n) {
  mach_vm_size_t got = 0;
  return mach_vm_read_overwrite(mach_task_self(), addr, n, (mach_vm_address_t)out, &got) ==
             KERN_SUCCESS &&
         got == n;
}

// Reads a NUL-terminated string without assuming the buffer after it is mapped.
static int read_cstr(u64 addr, char *out, size_t n) {
  size_t k = 0;
  for (; k + 1 < n; k++) {
    if (!safe_read(addr + k, &out[k], 1)) return 0;
    if (!out[k]) return 1;
  }
  out[k] = 0;
  return 1;
}

